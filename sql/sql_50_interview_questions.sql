--50.	Find customers who placed at least 3 orders, and display the first order date, last order date, and number of days between them. 
--Expected columns: customer_id customer_name order_count first_order_date last_order_date days_between_orders:
select c.customer_id, c.customer_name, count(o.order_id) AS order_count, min(o.order_date) AS first_order_date,
