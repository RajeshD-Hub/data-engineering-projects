--45.	For each user, find their longest consecutive login streak. 
--Expected columns: user_id longest_streak:
WITH numbered_logins AS (
select user_id, login_date, ROW_NUMBER() OVER(PARTITION BY user_id ORDER BY login_date) AS rank
from user_logins
),
login_groups AS (
select user_id, login_date, DATE_SUB(login_date, INTERVAL rn DAY) AS grp
from numbered_logins
),
streaks AS (
    select user_id, grp, COUNT(*) AS streak_length
    from login_groups
    group by user_id, grp
)
